fn request_body_size_bucket(body_bytes: usize) -> &'static str {
    if body_bytes <= 256 * 1024 {
        "le_256k"
    } else if body_bytes <= 1024 * 1024 {
        "le_1m"
    } else if body_bytes <= 2 * 1024 * 1024 {
        "le_2m"
    } else if body_bytes <= 4 * 1024 * 1024 {
        "le_4m"
    } else {
        "gt_4m"
    }
}

