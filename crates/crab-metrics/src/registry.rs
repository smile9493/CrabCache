#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum CacheTier {
    L0Moka,
    L1Redis,
    L2Semantic,
    Miss,
}

impl CacheTier {
    pub fn as_str(&self) -> &'static str {
        match self {
            CacheTier::L0Moka => "L0_moka",
            CacheTier::L1Redis => "L1_redis",
            CacheTier::L2Semantic => "L2_semantic",
            CacheTier::Miss => "miss",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LatencyKind {
    Upstream,
    TTFT,
    CacheFetch,
}

fn metric_consumer(consumer: Option<&str>) -> &str {
    consumer.unwrap_or("unknown")
}

fn metric_domain(domain: Option<&str>) -> &str {
    domain.unwrap_or("unclassified")
}

impl LatencyKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            LatencyKind::Upstream => "upstream",
            LatencyKind::TTFT => "ttft",
            LatencyKind::CacheFetch => "cache_fetch",
        }
    }
}

